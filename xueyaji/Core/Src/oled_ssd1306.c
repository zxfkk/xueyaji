static void OLED_WriteCmd(uint8_t cmd) {
    BSP_I2C_WriteReg(s_oled_bus, OLED_I2C_ADDR, 0x00U, cmd);
}

void OLED_Init(void) {
    /* 上电等待 50ms 确保 SSD1306 内部复位电路稳压完成 */
    HAL_Delay(50);

    /* 自动探测 OLED 接在 PB6/PB7 (I2C_BUS_1) 还是 PB10/PB11 (I2C_BUS_2) */
    if (BSP_I2C_CheckDevice(I2C_BUS_1, OLED_I2C_ADDR)) {
        s_oled_bus = I2C_BUS_1;
    } else if (BSP_I2C_CheckDevice(I2C_BUS_2, OLED_I2C_ADDR)) {
        s_oled_bus = I2C_BUS_2;
    } else {
        s_oled_bus = I2C_BUS_1;
    }

    static const uint8_t init_cmds[] = {
        0xAE,       /* 关闭显示 */
        0xD5, 0x80, /* 设置时钟分频因子 */
        0xA8, 0x3F, /* 设置驱动路数 (1/64 duty) */
        0xD3, 0x00, /* 设置显示偏移为 0 */
        0x40,       /* 设置起始行为第 0 行 */
        0x8D, 0x14, /* 开启内部 DC-DC 电荷泵 (核心指令) */
        0x20, 0x02, /* 页寻址模式 */
        0xA1,       /* 段重定义设置 (左右正常) */
        0xC8,       /* COM 扫描方向 (上下正常) */
        0xDA, 0x12, /* COM 硬件引脚配置 */
        0x81, 0xCF, /* 对比度设置 */
        0xD9, 0xF1, /* 预充电周期 */
        0xDB, 0x40, /* VCOMH 电压倍率 */
        0xA4,       /* 全局显示开启 */
        0xA6,       /* 正常显示 (非反相) */
        0xAF        /* 开启 OLED 面板显示 */
    };

    for (uint8_t i = 0; i < sizeof(init_cmds); i++) {
        OLED_WriteCmd(init_cmds[i]);
    }
    OLED_Clear();
    OLED_Refresh();
}

void OLED_Clear(void) {
    memset(s_oled_gram, 0, sizeof(s_oled_gram));
}

